/* 共享真实渲染器：网络题卡、选项、来源、转义和题图等待状态。浏览器另测实际图片加载。 */
'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const esc=v=>String(v??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const context=vm.createContext({window:{},console,URL,U:{esc},API:{ai:{}},icon:()=>'',assistantMark:()=>''});
vm.runInContext(fs.readFileSync('assets/js/shared/agent-chat.js','utf8'),context);
const chat=context.window.AgentChatView.create({safeMarkdown:true});
const question={id:'WQ1',title:'格式 <img src=x>',stem:'Write a program\\. Next\\, reverse the queue\\. Sample Output\\:',sourceUrl:'https://example.com/question',sourceTitle:'原题',images:[],options:[{label:'A',text:'`front == rear`'},{label:'B',text:'**先进先出**'}]};
const render=q=>chat.tpl({role:'ai',content:'已整理题卡',toolLog:[{kind:'web_question',question:q}]});
const html=render(question);
assert.match(html,/web-question__stem/);assert.match(html,/web-question__options/);assert.match(html,/<b>A\.<\/b>/);
assert.match(html,/Write a program\. Next, reverse the queue\./);assert.doesNotMatch(html.slice(html.indexOf('<article')),/\\[.,]/);
assert.match(html,/Sample Output:/);
assert.match(html,/<code>front == rear<\/code>/);assert.match(html,/<strong>先进先出<\/strong>/);
assert.doesNotMatch(html,/<img src=x/);assert.match(html,/target="_blank"/);assert.doesNotMatch(html,/tools__spinner/);
assert.match(render({...question,images:[{url:'https://example.com/figure.png',alt:'原题图'}],requiresImage:true}),/<article class="web-question" hidden>/);
assert.doesNotMatch(render({...question,requiresImage:true}),/<article class="web-question"/);
assert.doesNotMatch(render({...question,sourceUrl:'javascript:alert(1)'}),/<article class="web-question"/);
const pdf={...question,sourcePage:3,extractionMethod:'ocr',images:[{url:'/resources/web-question-pdfs/'+'a'.repeat(64)+'/question-3-1.png',alt:'PDF 第 3 页 · 原题截图'}],requiresImage:true};
assert.match(render(pdf),/PDF 原题/);assert.match(render(pdf),/扫描识别，以原图为准/);
assert.match(render(pdf),/href="https:\/\/example.com\/question#page=3"/);assert.match(render(pdf),/data-question-image-src="\/resources\/web-question-pdfs\//);
assert.match(render(pdf),/data-image-scale aria-label="图片缩放比例"/);assert.match(render(pdf),/data-image-open>查看大图/);
assert.match(render(pdf),/title="双击查看大图，或按 Enter 打开"/);assert.match(render(pdf),/class="web-question__image-viewport"/);
assert.doesNotMatch(render({...pdf,images:[{url:'/resources/web-question-pdfs/../../secret.png'}]}),/web-question--pdf/);
const code=context.window.AgentChatView.mdToHtml('`a\\.b`',{escapeHtml:true});assert.match(code,/a\\\.b/);
const plan={id:'P1',target:'student.page.practice',label:'打开练习',auto:true};
const confirmation=chat.tpl({role:'ai',content:'是否打开？',toolLog:[{kind:'ui_action',plan}]});
assert.match(confirmation,/data-agent-cancel/);assert.match(confirmation,/确认打开/);
console.log('[ok] 题面、选项、题图等待与来源分区，网页转义符清理，HTML 不执行，纯文字及缺图处理');
console.log('[ok] 题卡元数据不显示为运行中的工具，旧自动计划显示确认/取消');
